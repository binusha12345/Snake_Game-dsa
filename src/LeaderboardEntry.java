/**
 * Represents a single player's score entry on the leaderboard.
 */
public class LeaderboardEntry {

    private String name;
    private int score;

    public LeaderboardEntry(String name, int score) {
        this.name = name;
        this.score = score;
    }

    public String getName() {
        return name;
    }

    public int getScore() {
        return score;
    }

    public void setScore(int score) {
        this.score = score;
    }

    @Override
    public String toString() {
        return String.format("%-12s %d", name, score);
    }
}
